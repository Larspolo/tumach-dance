"""framework/tools/card.py checks a card for the owner: the owner gets only a complete card (owner, 2026-11-14)."""
import card

CONFIG = {"owner": "Lead", "owners": ["Lead", "Second"]}
STEP = ("## For the owner\nKind: setting\nMinutes: 3\nOnly the owner: the setting is in the account of the owner.\n"
        "Tried: the API with the token of the run → 403\n1. Open the page.\nReply: done\n")


def issue(body="", labels=("needs-human",), **more):
    return {"number": 7, "state": "open", "body": body, "labels": [{"name": x} for x in labels], **more}


def comment(body):
    return {"body": body + "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"}


def test_a_complete_step_card_has_no_fault():
    assert card.faults(card.card(issue(STEP))) == []
    for kind in card.STEP_KINDS:
        assert card.faults(STEP.split("\n", 1)[1].replace("setting", kind, 1)) == []


def test_a_step_card_says_why_only_the_owner_can_do_it_and_what_the_run_tried():
    for line, key in (("Only the owner:", "Only the owner"), ("Tried:", "Tried")):
        for value in (None, "", " nothing", " n/a", " -", " None."):
            text = "\n".join(x for x in STEP.splitlines() if not x.startswith(line))
            text += "" if value is None else f"\n{line}{value}"
            bad = card.faults(card.card(issue(text)))
            assert len(bad) == 1 and f"`{key}:`" in bad[0], (line, value)
    assert card.faults("Kind: step\nMinutes: 2\n- Only the owner: no machine has a bank card\n- Tried: no other route") == []


def test_a_card_with_no_step_needs_only_its_kind_and_the_minutes():
    for kind in sorted(set(card.KINDS) - set(card.STEP_KINDS)):
        assert card.faults(f"Kind: {kind}   (a note)\nMinutes: 2\nReply A or B.") == []
    assert len(card.faults("Reply A or B.")) == 2
    assert len(card.faults("Kind: decision\nMinutes: some\n")) == 1
    assert len(card.faults("Kind: riddle\nMinutes: 1\n")) == 1


def test_no_section_is_one_fault():
    assert len(card.faults(card.card(issue("## Goal\nKind: step\nMinutes: 1")))) == 1


def test_the_newest_section_is_the_card():
    old = "## For the owner\nKind: decision\nMinutes: 1\n"
    assert card.card(issue(old), [comment("a note"), comment(STEP), comment("no section")]).startswith("Kind: setting")
    assert card.card(issue(old), [comment("a note")]).startswith("Kind: decision")
    assert card.card(issue("## For the owner\nKind: play\nMinutes: 9\n\n## Verify\nKind: step\n")) == "Kind: play\nMinutes: 9"


def test_the_card_goes_to_its_owner():
    assert card.person(STEP, CONFIG) == "Lead"
    assert card.person(STEP + "For: @second\n", CONFIG) == "Second"
    assert card.person(STEP + "For: stranger\n", CONFIG) == "Lead"
    assert card.verdict(issue(STEP + "For: Second\n"), config=CONFIG) == ("assign", "Second")


def test_an_incomplete_card_goes_back_and_other_issues_are_skipped():
    what, bad = card.verdict(issue("Please run the script on your computer."), [comment("@Lead do this")], config=CONFIG)
    assert what == "back" and len(bad) == 1
    assert card.verdict(issue(""), [comment("Done. Please close it.")], config=CONFIG) == ("assign", "Lead")
    assert card.verdict(issue(""), sender="second", config=CONFIG)[0] == "skip"
    assert card.verdict(issue(STEP, labels=("P1",)), config=CONFIG)[0] == "skip"
    assert card.verdict(issue(STEP, state="closed"), config=CONFIG)[0] == "skip"
    assert card.verdict(issue(STEP, pull_request={}), config=CONFIG)[0] == "skip"


def test_an_epic_that_waits_for_an_answer_on_another_issue_keeps_its_label():
    epic = ("needs-human", "epic")
    assert card.verdict(issue("## Goal\nX", labels=epic), [comment("It waits for the answer on #8.")], config=CONFIG)[0] == "skip"
    assert card.verdict(issue(STEP, labels=epic), config=CONFIG) == ("assign", "Lead")
    assert card.verdict(issue("## For the owner\nKind: step\n", labels=epic), config=CONFIG)[0] == "back"


class Hub:
    """A false GitHub: one issue with its comments, and the list of the write calls."""

    def __init__(self, issue, comments=(), later=None):
        self.issue, self.comments, self.later, self.calls = issue, list(comments), later, []

    def api(self, path, method="GET", data=None):
        if method == "GET":
            return self.issue
        self.calls.append((method, path, data))
        return {}

    def pages(self, path):
        return self.comments

    def sleep(self, seconds):
        self.calls.append(("sleep", seconds, None))
        self.comments = self.comments + list(self.later or [])


def test_apply_assigns_a_complete_card_one_time():
    hub = Hub(issue(STEP))
    assert card.run(7, apply=True, api=hub.api, pages=hub.pages, config=CONFIG) == ("assign", "Lead")
    assert hub.calls == [("POST", "issues/7/assignees", {"assignees": ["Lead"]})]
    hub = Hub(issue(STEP, assignees=[{"login": "Second"}]))
    card.run(7, apply=True, api=hub.api, pages=hub.pages, config=CONFIG)
    assert hub.calls == []


def test_apply_takes_the_label_off_an_incomplete_card_and_says_what_it_needs():
    hub = Hub(issue("Run the script on your computer."))
    what, bad = card.run(7, apply=True, api=hub.api, pages=hub.pages, config=CONFIG)
    assert what == "back"
    assert [c[:2] for c in hub.calls] == [("DELETE", "issues/7/labels/needs-human"), ("POST", "issues/7/comments")]
    assert all(b in hub.calls[1][2]["body"] for b in bad)
    hub = Hub(issue("Run the script."))
    assert card.run(7, api=hub.api, pages=hub.pages, config=CONFIG)[0] == "back" and hub.calls == []


def test_a_card_that_comes_some_seconds_after_the_label_counts():
    hub = Hub(issue(""), later=[comment(STEP)])
    assert card.run(7, apply=True, wait=30, api=hub.api, pages=hub.pages, sleep=hub.sleep, config=CONFIG) == ("assign", "Lead")
    assert hub.calls == [("sleep", 30, None), ("POST", "issues/7/assignees", {"assignees": ["Lead"]})]


def test_the_text_mode_checks_a_file_with_no_network(tmp_path, capsys):
    good, bad = tmp_path / "good.md", tmp_path / "bad.md"
    good.write_text("The host gives no answer.\n\n" + STEP, encoding="utf-8")
    bad.write_text("Please change the network policy.", encoding="utf-8")
    assert card.main(["--text", str(good)]) == 0
    assert card.main(["--text", str(bad)]) == 1 and "## For the owner" in capsys.readouterr().out
