"""framework/tools/card.py takes an answered card off the list of the owner: the comment of the owner removes the label
`needs-human` and the owner as the assignee (owner, 2026-11-14)."""
import card

CONFIG = {"owner": "Lead", "owners": ["Lead", "Second"]}
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def issue(assignees=("Lead",), labels=("needs-human", "proposal"), **more):
    return {"number": 7, "state": "open", "body": "", "labels": [{"name": x} for x in labels],
            "assignees": [{"login": x} for x in assignees], **more}


def comment(login, body="C", **more):
    return {"id": 99, "user": {"login": login}, "body": body, **more}


def test_a_comment_of_the_owner_of_the_card_is_an_answer():
    assert card.answered(issue(), comment("Lead"), CONFIG)
    assert card.answered(issue(), comment("lead", "> an old line" + FOOTER.replace("\n", "\n> ") + "\n\nyes"), CONFIG)
    assert card.answered(issue(assignees=()), comment("Second"), CONFIG)          # a card from before the assignees
    assert card.answered(issue(assignees=("agent-login",)), comment("Lead"), CONFIG)


def test_other_comments_are_no_answer():
    assert not card.answered(issue(), comment("agent-login"), CONFIG)
    assert not card.answered(issue(), comment("Lead", "Started by a run." + FOOTER), CONFIG)      # a session of the owner
    assert not card.answered(issue(), comment("Lead", performed_via_github_app={"slug": "claude"}), CONFIG)
    assert not card.answered(issue(), comment("Second"), CONFIG)                   # the card is for the other owner
    assert not card.answered(issue(labels=("P1",)), comment("Lead"), CONFIG)
    assert not card.answered(issue(state="closed"), comment("Lead"), CONFIG)
    assert not card.answered(issue(pull_request={}), comment("Lead"), CONFIG)


class Hub:
    """A false GitHub: one issue and one comment, and the list of the write calls."""

    def __init__(self, issue, comment):
        self.issue, self.comment, self.calls = issue, comment, []

    def api(self, path, method="GET", data=None):
        if method == "GET":
            return self.comment if "/comments/" in path else self.issue
        self.calls.append((method, path, data))
        return {}


def test_an_answer_takes_the_label_and_the_assignee_off():
    hub = Hub(issue(assignees=("Lead", "Second")), comment("Lead"))
    assert card.answer(7, 99, apply=True, api=hub.api, config=CONFIG)
    assert hub.calls == [("DELETE", "issues/7/labels/needs-human", None),
                         ("DELETE", "issues/7/assignees", {"assignees": ["Lead"]})]


def test_an_answer_on_a_card_with_no_assignee_takes_only_the_label_off():
    hub = Hub(issue(assignees=()), comment("Lead"))
    assert card.answer(7, 99, apply=True, api=hub.api, config=CONFIG)
    assert hub.calls == [("DELETE", "issues/7/labels/needs-human", None)]


def test_no_answer_changes_nothing():
    hub = Hub(issue(), comment("agent-login"))
    assert not card.answer(7, 99, apply=True, api=hub.api, config=CONFIG) and hub.calls == []
    hub = Hub(issue(), comment("Lead"))
    assert card.answer(7, 99, api=hub.api, config=CONFIG) and hub.calls == []      # with no `apply`: only the result
